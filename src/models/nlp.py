# -*- coding: utf-8 -*-
"""Sentiment engine for the off-peak attraction page — own implementation.

Pipeline (all hand-written; scikit-learn appears only as an accuracy
benchmark):
  1. tokenizer     lowercase regex [a-z']{2,}, own stopword list that KEEPS
                   negators (not/no/never …) — dropping them would flip
                   sentiment on "not worth it"
  2. TF-IDF        sublinear tf, smoothed idf ln((1+N)/(1+df))+1, L2 rows;
                   min_df/max_df pruning, vocab cap 20k (scipy.sparse only as
                   matrix infrastructure, like NumPy)
  3. LogReg        binary logistic regression, full-batch gradient descent
                   with momentum + L2; own AUC (rank/Mann-Whitney)
  4. application   score attraction reviews -> rank attractions by positive
                   share, surface indicative terms

Training corpus: REAL TripAdvisor attraction reviews (Singapore, 195k rows,
HuggingFace mirror of a Kaggle dataset) — same domain as the product (short
city-attraction tourist reviews).

HK application corpus: no public downloadable HK attraction review corpus
exists (checked Kaggle/HuggingFace/GitHub, see report §Data). Per the course
spec's synthetic-data clause the HK layer therefore uses a CLEARLY LABELLED
synthetic demonstration corpus generated by make_hk_corpus() below — 12 real
HK attractions, review text assembled from phrase templates with realistic
positivity mixes, so the end-to-end product pipeline is demonstrable. The
sentiment model itself is trained and evaluated ONLY on real reviews.
"""
import json
import os
import re

import numpy as np
import pandas as pd
import scipy.sparse as sp

RNG = np.random.default_rng(7005)

# negators deliberately absent from this stoplist
STOP = """a an the and or but if while of to in on at for with about against
between into through during before after above below from up down out off
over under again further then once here there when where why how all any
both each few more most other some such only own same so than too very s t
can will just don should now i me my we our you your he she it they them his
her its this that these those what which who whom am is are was were be been
being have has had having do does did as by at from""".split()
STOPSET = set(STOP)

TOKEN = re.compile(r"[a-z']{2,}")
NEGATORS = {"not", "no", "never", "nothing", "without", "hardly", "barely"}


def tokenize(text):
    """Tokens with negation-scope marking: a token directly after a negator
    gets a NOT_ prefix ("not worth" -> NOT_worth), so the unigram model can
    separate "worth" from its negated use — otherwise "not worth the price"
    reads as positive to a bag-of-words model (observed 29% of negative
    synthetic reviews misclassified before this fix; see report)."""
    toks = [w for w in TOKEN.findall(str(text).lower()) if w not in STOPSET]
    out = []
    for i, w in enumerate(toks):
        if w in NEGATORS:
            continue
        out.append("NOT_" + w if (i > 0 and toks[i - 1] in NEGATORS) else w)
    return out


# ---------------- TF-IDF (own) ----------------
class TfIdf:
    def __init__(self, min_df=5, max_df_ratio=0.5, max_features=20000):
        self.min_df = min_df
        self.max_df_ratio = max_df_ratio
        self.max_features = max_features

    def fit(self, docs):
        df = {}
        for d in docs:
            for w in set(d):
                df[w] = df.get(w, 0) + 1
        n = len(docs)
        vocab = {w: c for w, c in df.items() if c >= self.min_df and c <= self.max_df_ratio * n}
        if len(vocab) > self.max_features:
            vocab = dict(sorted(vocab.items(), key=lambda kv: -kv[1])[: self.max_features])
        self.vocab_ = {w: j for j, w in enumerate(sorted(vocab))}
        self.idf_ = np.log((1 + n) / (1 + np.array(list(vocab.values()), dtype=float))) + 1
        return self

    def transform(self, docs):
        """Sublinear tf x idf, L2-normalised rows, CSR."""
        indptr, indices, data = [0], [], []
        for d in docs:
            cnt = {}
            for w in d:
                j = self.vocab_.get(w)
                if j is not None:
                    cnt[j] = cnt.get(j, 0) + 1
            norm = 0.0
            tf = {}
            for j, c in cnt.items():
                v = (1 + np.log(c)) * self.idf_[j]
                tf[j] = v
                norm += v * v
            norm = np.sqrt(norm) + 1e-12
            for j, v in tf.items():
                indices.append(j)
                data.append(v / norm)
            indptr.append(len(indices))
        return sp.csr_matrix((data, indices, indptr), shape=(len(docs), len(self.vocab_)))


# ---------------- logistic regression (own) ----------------
class LogReg:
    def __init__(self, lr=3e-4, epochs=800, l2=1e-3, momentum=0.9, balanced=True):
        self.lr, self.epochs, self.l2, self.momentum = lr, epochs, l2, momentum
        self.balanced = balanced

    @staticmethod
    def _sigmoid(z):
        return 1.0 / (1.0 + np.exp(-np.clip(z, -30, 30)))

    def fit(self, X, y):
        """Full-batch gradient descent with classical momentum on the SUM
        gradient (not the mean — see below):
             v <- mu*v - lr*grad ;  w <- w + v

        balanced=True reweights classes to equal total mass (the
        class_weight='balanced' formulation n / (2 * n_class)). The review
        corpus is ~97% positive; without balancing the intercept alone
        (+2.7 logits) pushed nearly every short review to 'positive',
        which destroys the attraction RANKING the product needs. With mean
        gradients the reweighted positive residual is ~1/30 of a sample, so
        content-word weights learn ~100x too slowly for plain GD — hence the
        sum gradient with a small lr (equivalent to lr=0.1 on the mean
        gradient of this corpus, but scale-aware)."""
        n, d = X.shape
        if self.balanced:
            sw = np.where(y == 1, n / (2.0 * max((y == 1).sum(), 1)),
                          n / (2.0 * max((y == 0).sum(), 1)))
        else:
            sw = np.ones(n)
        self.w_ = np.zeros(d)
        self.b_ = 0.0
        vw, vb = np.zeros(d), 0.0
        for _ in range(self.epochs):
            p = self._sigmoid(X @ self.w_ + self.b_)
            r = (p - y) * sw
            gw = np.asarray(X.T @ r).ravel() + self.l2 * self.w_
            gb = float(np.sum(r))
            vw = self.momentum * vw - self.lr * gw
            vb = self.momentum * vb - self.lr * gb
            self.w_ += vw
            self.b_ += vb
        return self

    def predict_proba(self, X):
        return self._sigmoid(X @ self.w_ + self.b_)


def auc_own(y, p):
    """AUC via rank statistics (Mann-Whitney U)."""
    order = np.argsort(p)
    ranks = np.empty(len(p))
    ranks[order] = np.arange(1, len(p) + 1)
    # average ranks for ties
    s = pd.Series(p)
    ranks = s.rank(method="average").values
    pos = y == 1
    return float((ranks[pos].sum() - pos.sum() * (pos.sum() + 1) / 2) / (pos.sum() * (~pos).sum()))


