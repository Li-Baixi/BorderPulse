"""Sentiment engine for the off-peak attraction page — own implementation.
Primary author: Lu Zengyi (TF-IDF + class-balanced LogReg, negation scope).


Pipeline (all hand-written; scikit-learn appears only as an accuracy
benchmark):
  1. tokenizer     lowercase regex [a-z']{2,}, own stopword list that KEEPS
                   negators (not/no/never …) — dropping them would flip
                   sentiment on "not worth it"
  2. TF-IDF        sublinear tf, smoothed idf ln((1+N)/(1+df))+1, L2 rows;
                   min_df/max_df pruning, vocab cap 20k (scipy.sparse only as
                   matrix infrastructure, like NumPy)
  3. LogReg        binary logistic regression, full-batch gradient descent
                   with momentum + L2; own AUC (rank/Mann-Whitney)
  4. application   score attraction reviews -> rank attractions by positive
                   share, surface indicative terms

Training corpus: REAL TripAdvisor attraction reviews (Singapore, 195k rows,
HuggingFace mirror of a Kaggle dataset) — same domain as the product (short
city-attraction tourist reviews).

HK application corpus: no public downloadable HK attraction review corpus
exists (checked Kaggle/HuggingFace/GitHub, see report §Data). Per the course
spec's synthetic-data clause the HK layer therefore uses a CLEARLY LABELLED
synthetic demonstration corpus generated by make_hk_corpus() below — 12 real
HK attractions, review text assembled from phrase templates with realistic
positivity mixes, so the end-to-end product pipeline is demonstrable. The
sentiment model itself is trained and evaluated ONLY on real reviews.

【中文说明 —— 景点评论情感引擎（错峰出行页的数据来源）】
作用：给"错峰景点"页排序——哪些景点口碑好、什么时候去人少。
流程（全部手写；scikit-learn 只作准确率基准对照）：
  1) 分词器   小写正则 [a-z']{2,}，自备停用词表但保留否定词
             （not/no/never…）——丢掉它们会把 "not worth" 读成好评
  2) TF-IDF  次线性 tf、平滑 idf、行 L2 归一化；
             min_df/max_df 剪枝、词表上限 2 万（scipy.sparse 只当
             稀疏矩阵基础设施用，地位同 NumPy）
  3) 逻辑回归 二分类、全批梯度下降 + 动量 + L2；AUC 也是自己实现的
             （秩统计 / Mann-Whitney）
  4) 应用     给景点评论打分 → 按好评率排景点、提炼指示性关键词
训练语料：真实 TripAdvisor 景点评论（新加坡，19.5 万行）——与产品
同域（短途城市景点游客评论）。
香港应用语料：没有公开可下载的香港景点评论数据集（已查证，见报告）。
按课程规范的合成数据条款，香港层使用明确标注的合成演示语料
（make_hk_corpus() 生成：12 个真实香港景点 + 短语模板拼装、
真实的好评率先验），使产品端到端可演示。情感模型本身只在
真实评论上训练和评估。
"""
