RNG = np.random.default_rng(7005)   # 中文：固定种子（7005 = 课程号）→ 全流程可复现

# negators deliberately absent from this stoplist
# 中文：自备停用词表。注意：否定词（not/no/never…）故意【不】在表里——
# 它们承担"翻转情感"的重任，停掉就废了（见 tokenize）。
STOP = """a an the and or but if while of to in on at for with about against
between into through during before after above below from up down out off
over under again further then once here there when where why how all any
both each few more most other some such only own same so than too very s t
can will just don should now i me my we our you your he she it they them his
her its this that these those what which who whom am is are was were be been
being have has had having do does did as by at from""".split()
STOPSET = set(STOP)

TOKEN = re.compile(r"[a-z']{2,}")   # 中文：只留 ≥2 字符的小写字母/撇号串
NEGATORS = {"not", "no", "never", "nothing", "without", "hardly", "barely"}   # 中文：否定词表


def tokenize(text):
    """Tokens with negation-scope marking: a token directly after a negator
    gets a NOT_ prefix ("not worth" -> NOT_worth), so the unigram model can
    separate "worth" from its negated use — otherwise "not worth the price"
    reads as positive to a bag-of-words model (observed 29% of negative
    synthetic reviews misclassified before this fix; see report).
    【中文】否定范围标记：紧跟否定词后面的那个词加 NOT_ 前缀
    （"not worth" → NOT_worth）。这样一元模型就能区分 "worth" 的
    肯定用法和被否定的用法——否则 "not worth the price" 在词袋模型
    眼里就是一堆褒义词（修复前 29% 的差评被误判为好评，见报告）。"""
    toks = [w for w in TOKEN.findall(str(text).lower()) if w not in STOPSET]
    out = []
    for i, w in enumerate(toks):
        if w in NEGATORS:
            continue                                    # 中文：否定词本身不进词表
        out.append("NOT_" + w if (i > 0 and toks[i - 1] in NEGATORS) else w)
    return out


# ---------------- TF-IDF (own) ----------------
class TfIdf:
    def __init__(self, min_df=5, max_df_ratio=0.5, max_features=20000):
        self.min_df = min_df
        self.max_df_ratio = max_df_ratio
        self.max_features = max_features

    def fit(self, docs):
        # 中文：统计每个词的文档频率 df → 按 min_df/max_df 剪枝 →
        # 超过词表上限时按 df 降序截断。
        df = {}
        for d in docs:
            for w in set(d):
                df[w] = df.get(w, 0) + 1
        n = len(docs)
        vocab = {w: c for w, c in df.items() if c >= self.min_df and c <= self.max_df_ratio * n}
        if len(vocab) > self.max_features:
            # tie-break on the word itself: count ties must not depend on
            # dict/set iteration order (PYTHONHASHSEED), or every rerun
            # truncates a slightly different vocabulary
            # 中文：df 相同的词按字母序决胜负——不能依赖 dict/set 的
            # 迭代顺序（受 PYTHONHASHSEED 影响），否则每次重跑截出的
            # 词表都不一样，结果不可复现。
            vocab = dict(sorted(vocab.items(), key=lambda kv: (-kv[1], kv[0]))[: self.max_features])
        # idf MUST be built in the same order as the index mapping below.
        # (Bug caught in final review: building it from dict insertion order
        # attached each word a random other word's idf — consistent within a
        # run, so metrics looked fine, but it was not the intended TF-IDF.)
        # 中文：idf 必须与下面的词→编号映射按同一顺序构造。
        # （终审时抓到的 bug：若按 dict 插入顺序建 idf，每个词会拿到
        # 另一个随机词的 idf——单次运行内部自洽，指标看着正常，
        # 但那根本不是想要的 TF-IDF。）
        words = sorted(vocab)
        self.vocab_ = {w: j for j, w in enumerate(words)}
        self.idf_ = np.log((1 + n) / (1 + np.array([vocab[w] for w in words], dtype=float))) + 1
        return self

    def transform(self, docs):
        """Sublinear tf x idf, L2-normalised rows, CSR."""
        # 中文：文档 → 稀疏矩阵。每个词：值 = (1+log(词频)) × idf
        # （次线性 tf，压制高频词），整行 L2 归一化，按 CSR 三元组拼装。
        indptr, indices, data = [0], [], []
        for d in docs:
            cnt = {}
            for w in d:
                j = self.vocab_.get(w)
                if j is not None:                       # 中文：词表外的词直接跳过
                    cnt[j] = cnt.get(j, 0) + 1
            norm = 0.0
            tf = {}
            for j, c in cnt.items():
                v = (1 + np.log(c)) * self.idf_[j]      # 中文：次线性 tf × idf
                tf[j] = v
                norm += v * v
            norm = np.sqrt(norm) + 1e-12                # 中文：行 L2 范数（防除零）
            for j, v in tf.items():
                indices.append(j)
                data.append(v / norm)
            indptr.append(len(indices))
        return sp.csr_matrix((data, indices, indptr), shape=(len(docs), len(self.vocab_)))


# ---------------- logistic regression (own) ----------------
class LogReg:
    def __init__(self, lr=3e-4, epochs=800, l2=1e-3, momentum=0.9, balanced=True):
        self.lr, self.epochs, self.l2, self.momentum = lr, epochs, l2, momentum
        self.balanced = balanced

    @staticmethod
    def _sigmoid(z):
        return 1.0 / (1.0 + np.exp(-np.clip(z, -30, 30)))

    def fit(self, X, y):
        """Full-batch gradient descent with classical momentum on the SUM
        gradient (not the mean — see below):
             v <- mu*v - lr*grad ;  w <- w + v

        balanced=True reweights classes to equal total mass (the
        class_weight='balanced' formulation n / (2 * n_class)). The review
        corpus is ~97% positive; without balancing the intercept alone
        (+2.7 logits) pushed nearly every short review to 'positive',
        which destroys the attraction RANKING the product needs. With mean
        gradients the reweighted positive residual is ~1/30 of a sample, so
        content-word weights learn ~100x too slowly for plain GD — hence the
        sum gradient with a small lr (equivalent to lr=0.1 on the mean
        gradient of this corpus, but scale-aware).
        【中文】要点：语料约 97% 是好评——不做类别平衡时，光靠截距
        （+2.7 个 logit）就能把几乎所有短评判成"好评"，产品需要的
        景点排序会失效。balanced=True 把两类各加权到总质量相等
        （即 sklearn class_weight='balanced' 的公式）。用"梯度和"而非
        "梯度均值"：平衡后正类残差每条约只有 1/30 样本的分量，
        均值梯度下实义词权重学得慢约 100 倍；小学习率 × 梯度和
        等价于均值梯度 lr=0.1，但对语料规模不敏感。"""
        n, d = X.shape
        if self.balanced:
            # 中文：类别平衡权重 n / (2 × 该类样本数)，两类总质量相等
            sw = np.where(y == 1, n / (2.0 * max((y == 1).sum(), 1)),
                          n / (2.0 * max((y == 0).sum(), 1)))
        else:
            sw = np.ones(n)
        self.w_ = np.zeros(d)
        self.b_ = 0.0
        vw, vb = np.zeros(d), 0.0                       # 中文：动量速度项
        for _ in range(self.epochs):
            p = self._sigmoid(X @ self.w_ + self.b_)    # 中文：当前预测概率
            r = (p - y) * sw                            # 中文：加权残差
            gw = np.asarray(X.T @ r).ravel() + self.l2 * self.w_   # 中文：权重梯度 + L2 正则
            gb = float(np.sum(r))                       # 中文：截距梯度（不正则）
            vw = self.momentum * vw - self.lr * gw      # 中文：经典动量更新
            vb = self.momentum * vb - self.lr * gb
            self.w_ += vw
            self.b_ += vb
        return self

    def predict_proba(self, X):
        # 中文：P(好评) = sigmoid(线性得分)
        return self._sigmoid(X @ self.w_ + self.b_)


def auc_own(y, p):
    """AUC via rank statistics (Mann-Whitney U); average ranks for ties."""
    # 中文：自己实现的 AUC——把预测分数换成秩（并列取平均秩），
    # 好评秩和减去随机基线再除以两类配对数（Mann-Whitney U 统计量）。
    ranks = pd.Series(p).rank(method="average").values
    pos = y == 1
    return float((ranks[pos].sum() - pos.sum() * (pos.sum() + 1) / 2) / (pos.sum() * (~pos).sum()))


