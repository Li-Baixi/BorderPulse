def make_hk_corpus(n_per_attr=40):
    """SYNTHETIC demonstration corpus (see module docstring): each review
    assembles 1 neutral connective + 2 sentiment-bearing phrases drawn from
    the attraction's positive-share prior. Label = the sentiment bucket the
    phrases came from (binary; the engine never sees the label).
    【中文】合成演示语料：每条评论 = 1 句中性开头 + 2 个情感短语；
    抽正/负短语的概率由该景点的好评率先验决定。标签就是所抽短语的
    桶（情感引擎从头到尾看不到标签），事后用 label-agreement 做 sanity。"""
    docs, labels, attr_ids = [], [], []
    for i, (en, _cn, pos_share, _tip) in enumerate(HK_ATTRACTIONS):
        for _ in range(n_per_attr):
            # 中文：开头句 = 景点名 + 一句中性过渡语（模拟真实评论的铺垫）
            lead = en + " — " + RNG.choice(NEUTRAL_CONNECT)
            if RNG.random() < pos_share:               # 中文：按先验概率抽正/负短语
                body = " ".join(RNG.choice(POS_PHRASES, 2, replace=False))
                lab = 1
            else:
                body = " ".join(RNG.choice(NEG_PHRASES, 2, replace=False))
                lab = 0
            docs.append(tokenize(lead + ". " + body))
            labels.append(lab)
            attr_ids.append(i)
    return docs, np.array(labels), np.array(attr_ids)


# ---------------- training on the real corpus ----------------
def load_real(path="data/raw/sg_tripadvisor.csv"):
    # 中文：读真实 TripAdvisor 评论。只留 1/2/4/5 星（3 星情感模糊，
    # 弃用），标题拼正文作为文档；标签 = 是否 ≥4 星（二分类）。
    df = pd.read_csv(path, low_memory=False)
    rating = pd.to_numeric(df["review_rating"], errors="coerce")
    keep = rating.notna() & rating.isin([1, 2, 4, 5]) & df["review_text"].notna()
    df, rating = df[keep], rating[keep]
    docs = [tokenize((str(t) + ". " + str(x))) for t, x in
            zip(df["review_title"], df["review_text"])]
    y = (rating >= 4).astype(int).values
    return docs, y


def train_sentiment(path="data/raw/sg_tripadvisor.csv"):
    # 中文：完整训练流程：90/10 随机划分 → TF-IDF → 自写 LogReg →
    # sklearn 同设置对照（仅作基准）→ 返回引擎与各项指标。
    docs, y = load_real(path)
    n = len(docs)
    idx = RNG.permutation(n)                            # 中文：固定 RNG → 划分可复现
    tr, te = idx[: int(n * 0.9)], idx[int(n * 0.9):]

    vec = TfIdf().fit([docs[i] for i in tr])            # 中文：词表只用训练集建（防泄漏）
    Xtr, Xte = vec.transform([docs[i] for i in tr]), vec.transform([docs[i] for i in te])

    own = LogReg().fit(Xtr, y[tr])
    p = own.predict_proba(Xte)
    acc = float(((p > 0.5) == y[te]).mean())
    auc = auc_own(y[te], p)

    from sklearn.linear_model import LogisticRegression  # benchmark ONLY
    # 中文：sklearn 仅作准确率基准对照（课程规则），不进产品
    skb = LogisticRegression(max_iter=1000, C=10,
                             class_weight="balanced").fit(Xtr, y[tr])
    psk = skb.decision_function(Xte)
    acc_sk = float(((psk > 0) == y[te]).mean())
    auc_sk = auc_own(y[te], 1 / (1 + np.exp(-psk)))

    return {
        "vec": vec, "model": own, "n_train": len(tr), "n_test": len(te),
        "acc": acc, "auc": auc, "acc_sk": acc_sk, "auc_sk": auc_sk,
        "vocab": len(vec.vocab_),
    }


def score_attractions(art):
    """Apply the trained engine to the synthetic HK corpus: positive share per
    attraction + top indicative terms + label-agreement sanity check.
    【中文】把训练好的引擎应用到合成香港语料：输出每个景点的好评率、
    指示性关键词、以及与真实标签的一致率（sanity 检查）。"""
    docs, labels, attr_ids = make_hk_corpus()
    X = art["vec"].transform(docs)                      # 中文：同一分词器/词表转换
    p = art["model"].predict_proba(X)                   # 中文：每条评论的 P(好评)
    agree = float(((p > 0.5) == labels).mean())         # 中文：与隐藏标签的一致率
    inv = {j: w for w, j in art["vec"].vocab_.items()}  # 中文：编号→词 反查表
    out = []
    for i, (en, cn, _prior, tip) in enumerate(HK_ATTRACTIONS):
        m = attr_ids == i                               # 中文：该景点的全部评论
        pos_share = float((p[m] > 0.5).mean())          # 中文：好评率 = 预测为正的比例
        # indicative terms: highest mean tf-idf among predicted-positive reviews,
        # excluding the attraction's own name tokens (uninformative)
        # 中文：指示词 = 预测为好评的评论里平均 tf-idf 最高的词
        # （剔除景点名本身的词——那不携带评价信息）
        name_toks = set(tokenize(en))
        Xp = X[m][np.asarray(p[m] > 0.5).ravel()]
        if Xp.shape[0]:
            mean_vec = np.asarray(Xp.mean(axis=0)).ravel()
            topj = np.argsort(mean_vec)[::-1]
            terms = [inv[j] for j in topj
                     if mean_vec[j] > 0 and inv[j] not in name_toks][:6]
        else:
            terms = []
        out.append({"en": en, "cn": cn, "pos": round(pos_share, 3),
                    "n": int(m.sum()), "terms": terms, "tip": tip})
    out.sort(key=lambda d: -d["pos"])                   # 中文：按好评率降序 = 前端展示顺序
    return out, agree


def main():
    # 中文：命令行入口：训练 → 打印指标 → 给景点打分 → 写 docs/nlp.json
    # （前端错峰景点页加载的就是这个文件）。
    art = train_sentiment()
    print("real corpus: train %d / test %d | own acc %.3f auc %.3f | sklearn acc %.3f auc %.3f | vocab %d"
          % (art["n_train"], art["n_test"], art["acc"], art["auc"],
             art["acc_sk"], art["auc_sk"], art["vocab"]))
    ranked, agree = score_attractions(art)
    print("synthetic HK corpus label-agreement (sanity): %.3f" % agree)
    for d in ranked:
        print("  %.0f%%  %s (%s) — %s" % (d["pos"] * 100, d["cn"], d["en"], ", ".join(d["terms"][:4])))
    os.makedirs("docs", exist_ok=True)
    # 中文：紧凑 JSON（separators 去空格）→ 文件小、加载快
